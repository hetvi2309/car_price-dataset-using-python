lower_limit = Q1 - 1.5 * IQR
upper_limit = Q3 + 1.5 * IQR

# Remove outliers

cleaned_df = color_price_df[
    (color_price_df['sellingprice'] >= lower_limit) &
    (color_price_df['sellingprice'] <= upper_limit)
]

# Display shape before and after removing outliers

